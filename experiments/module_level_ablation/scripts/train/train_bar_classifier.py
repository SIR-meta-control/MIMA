#!/usr/bin/env python3
"""
Train a PyTorch classifier for p(v | vreq).

The model predicts:
  [P(4-bar), P(8-bar), P(6-bar)]
from:
  vreq = [x, y, z, load, inspect, pack]
"""

from __future__ import annotations

import argparse
import copy
import json
import sys
from collections import defaultdict
from pathlib import Path

def find_project_root(start: Path) -> Path:
    for parent in start.resolve().parents:
        if (parent / "models" / "gvae").is_dir():
            return parent
    raise RuntimeError("Could not find project root containing models/gvae")


PROJECT_ROOT = find_project_root(Path(__file__))
sys.path.insert(0, str(PROJECT_ROOT / "models"))
sys.path.insert(0, str(PROJECT_ROOT))

import numpy as np
import torch
from torch import nn
from torch.nn import functional as F
from torch.utils.data import DataLoader, TensorDataset

from gvae.networks.bar_classifier import BarClassifier
from gvae.core.constants import BAR_ORDER, VREQ_FORMAT


OUTPUT_FORMAT = [f"P({bar_type})" for bar_type in BAR_ORDER]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Train bar type classifier.")
    parser.add_argument(
        "--dataset",
        default="datasets/processed_dataset/bar_classifier_dataset.jsonl",
        help="Dense classifier dataset generated by build_bar_classifier_dataset.py.",
    )
    parser.add_argument("--output-dir", default="ckpts/bar_classifier")
    parser.add_argument("--hidden-dim", type=int, default=64)
    parser.add_argument("--dropout", type=float, default=0.0)
    parser.add_argument("--epochs", type=int, default=250)
    parser.add_argument("--batch-size", type=int, default=512)
    parser.add_argument("--lr", type=float, default=1e-3)
    parser.add_argument("--weight-decay", type=float, default=1e-4)
    parser.add_argument("--val-ratio", type=float, default=0.2)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--patience", type=int, default=40)
    parser.add_argument("--min-delta", type=float, default=1e-5)
    parser.add_argument(
        "--device",
        default="auto",
        choices=["auto", "cpu", "cuda"],
        help="Training device. auto uses cuda when available.",
    )
    parser.add_argument("--log-interval", type=int, default=10)
    return parser.parse_args()


def read_jsonl(path: Path):
    with path.open("r") as f:
        for line in f:
            line = line.strip()
            if line:
                yield json.loads(line)


def write_json(path: Path, obj: dict) -> None:
    with path.open("w") as f:
        json.dump(obj, f, indent=2)


def load_dataset(path: Path) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    xs = []
    ys = []
    tasks = []

    for row in read_jsonl(path):
        xs.append(row["vreq"])
        ys.append(row["v_probs"])
        tasks.append(row["task"])

    if not xs:
        raise ValueError(f"No rows found in {path}")

    x = np.asarray(xs, dtype=np.float32)
    y = np.asarray(ys, dtype=np.float32)
    y_sum = y.sum(axis=1, keepdims=True)
    valid = y_sum[:, 0] > 0.0
    x = x[valid]
    y = y[valid] / y_sum[valid]
    tasks_array = np.asarray(tasks, dtype=object)[valid]
    return x, y, tasks_array


def make_stratified_split(
    tasks: np.ndarray,
    targets: np.ndarray,
    val_ratio: float,
    seed: int,
) -> tuple[np.ndarray, np.ndarray]:
    rng = np.random.default_rng(seed)
    groups: dict[tuple[str, int], list[int]] = defaultdict(list)
    hard_labels = np.argmax(targets, axis=1)

    for idx, (task, hard_label) in enumerate(zip(tasks.tolist(), hard_labels.tolist())):
        groups[(str(task), int(hard_label))].append(idx)

    train_idx = []
    val_idx = []
    for indices in groups.values():
        indices = list(indices)
        rng.shuffle(indices)
        if len(indices) < 2:
            train_idx.extend(indices)
            continue
        val_count = max(1, int(round(len(indices) * val_ratio)))
        val_count = min(val_count, len(indices) - 1)
        val_idx.extend(indices[:val_count])
        train_idx.extend(indices[val_count:])

    rng.shuffle(train_idx)
    rng.shuffle(val_idx)
    return np.asarray(train_idx, dtype=np.int64), np.asarray(val_idx, dtype=np.int64)


def normalize_inputs(
    x_train: np.ndarray,
    x_val: np.ndarray,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    mean = x_train.mean(axis=0, dtype=np.float64).astype(np.float32)
    std = x_train.std(axis=0, dtype=np.float64).astype(np.float32)
    std[std < 1e-6] = 1.0
    return (x_train - mean) / std, (x_val - mean) / std, mean, std


def soft_cross_entropy(logits: torch.Tensor, targets: torch.Tensor) -> torch.Tensor:
    log_probs = F.log_softmax(logits, dim=-1)
    return -(targets * log_probs).sum(dim=-1).mean()


def make_loader(
    x: np.ndarray,
    y: np.ndarray,
    batch_size: int,
    seed: int,
    shuffle: bool,
) -> DataLoader:
    dataset = TensorDataset(torch.from_numpy(x), torch.from_numpy(y))
    generator = torch.Generator()
    generator.manual_seed(seed)
    return DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        generator=generator,
    )


def evaluate(
    model: nn.Module,
    x: np.ndarray,
    y: np.ndarray,
    tasks: np.ndarray,
    device: torch.device,
    batch_size: int,
) -> dict:
    model.eval()
    probs_chunks = []

    loader = make_loader(x, y, batch_size, seed=0, shuffle=False)
    with torch.no_grad():
        for batch_x, _ in loader:
            logits = model(batch_x.to(device))
            probs_chunks.append(F.softmax(logits, dim=-1).cpu().numpy())

    probs = np.concatenate(probs_chunks, axis=0)
    loss = -np.sum(y * np.log(probs + 1e-12)) / len(x)
    prob_mae = float(np.mean(np.abs(probs - y)))
    hard_acc = float(np.mean(np.argmax(probs, axis=1) == np.argmax(y, axis=1)))
    brier = float(np.mean(np.sum((probs - y) ** 2, axis=1)))

    by_task = {}
    for task in sorted(set(tasks.tolist())):
        mask = tasks == task
        if not np.any(mask):
            continue
        task_probs = probs[mask]
        task_targets = y[mask]
        by_task[str(task)] = {
            "count": int(mask.sum()),
            "loss": float(
                -np.sum(task_targets * np.log(task_probs + 1e-12)) / mask.sum()
            ),
            "prob_mae": float(np.mean(np.abs(task_probs - task_targets))),
            "hard_acc": float(
                np.mean(
                    np.argmax(task_probs, axis=1)
                    == np.argmax(task_targets, axis=1)
                )
            ),
            "mean_target_probs": task_targets.mean(axis=0).astype(float).tolist(),
            "mean_pred_probs": task_probs.mean(axis=0).astype(float).tolist(),
        }

    return {
        "loss": float(loss),
        "prob_mae": prob_mae,
        "hard_acc": hard_acc,
        "brier": brier,
        "mean_target_probs": y.mean(axis=0).astype(float).tolist(),
        "mean_pred_probs": probs.mean(axis=0).astype(float).tolist(),
        "by_task": by_task,
    }


def select_device(name: str) -> torch.device:
    if name == "auto":
        return torch.device("cuda" if torch.cuda.is_available() else "cpu")
    if name == "cuda" and not torch.cuda.is_available():
        raise RuntimeError("CUDA was requested but torch.cuda.is_available() is false")
    return torch.device(name)


def save_checkpoint(
    output_dir: Path,
    model: nn.Module,
    mean: np.ndarray,
    std: np.ndarray,
    config: dict,
    metrics: dict,
) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    checkpoint = {
        "model_state": model.state_dict(),
        "model_config": {
            "input_dim": len(VREQ_FORMAT),
            "hidden_dim": int(config["hidden_dim"]),
            "output_dim": len(OUTPUT_FORMAT),
            "dropout": float(config["dropout"]),
        },
        "input_mean": mean.astype(float).tolist(),
        "input_std": std.astype(float).tolist(),
        "input_format": VREQ_FORMAT,
        "output_format": OUTPUT_FORMAT,
        "v_mapping": {str(key): value for key, value in enumerate(BAR_ORDER)},
        "config": config,
        "metrics": metrics,
    }
    torch.save(checkpoint, output_dir / "bar_classifier.pt")
    write_json(output_dir / "bar_classifier_metrics.json", metrics)
    write_json(output_dir / "bar_classifier_config.json", config)


def main() -> None:
    args = parse_args()
    torch.manual_seed(args.seed)
    np.random.seed(args.seed)

    dataset_path = Path(args.dataset)
    output_dir = Path(args.output_dir)
    device = select_device(args.device)

    x, y, tasks = load_dataset(dataset_path)
    train_idx, val_idx = make_stratified_split(tasks, y, args.val_ratio, args.seed)
    x_train_raw, y_train, tasks_train = x[train_idx], y[train_idx], tasks[train_idx]
    x_val_raw, y_val, tasks_val = x[val_idx], y[val_idx], tasks[val_idx]
    x_train, x_val, mean, std = normalize_inputs(x_train_raw, x_val_raw)

    train_loader = make_loader(
        x_train,
        y_train,
        batch_size=args.batch_size,
        seed=args.seed,
        shuffle=True,
    )

    model = BarClassifier(
        input_dim=x.shape[1],
        hidden_dim=args.hidden_dim,
        output_dim=y.shape[1],
        dropout=args.dropout,
    ).to(device)
    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=args.lr,
        weight_decay=args.weight_decay,
    )

    best_val_loss = float("inf")
    best_state = copy.deepcopy(model.state_dict())
    best_epoch = 0
    epochs_without_improvement = 0
    history = []

    print(
        f"Training on {len(train_idx)} rows, validating on {len(val_idx)} rows, "
        f"device={device}"
    )

    for epoch in range(1, args.epochs + 1):
        model.train()
        train_losses = []
        for batch_x, batch_y in train_loader:
            batch_x = batch_x.to(device)
            batch_y = batch_y.to(device)
            optimizer.zero_grad(set_to_none=True)
            logits = model(batch_x)
            loss = soft_cross_entropy(logits, batch_y)
            loss.backward()
            optimizer.step()
            train_losses.append(float(loss.detach().cpu().item()))

        train_metrics = evaluate(
            model,
            x_train,
            y_train,
            tasks_train,
            device=device,
            batch_size=args.batch_size,
        )
        val_metrics = evaluate(
            model,
            x_val,
            y_val,
            tasks_val,
            device=device,
            batch_size=args.batch_size,
        )

        row = {
            "epoch": epoch,
            "train_loss": train_metrics["loss"],
            "val_loss": val_metrics["loss"],
            "val_prob_mae": val_metrics["prob_mae"],
            "val_hard_acc": val_metrics["hard_acc"],
            "lr": optimizer.param_groups[0]["lr"],
        }
        history.append(row)

        if val_metrics["loss"] < best_val_loss - args.min_delta:
            best_val_loss = val_metrics["loss"]
            best_state = copy.deepcopy(model.state_dict())
            best_epoch = epoch
            epochs_without_improvement = 0
        else:
            epochs_without_improvement += 1

        if (
            epoch == 1
            or epoch % args.log_interval == 0
            or epochs_without_improvement >= args.patience
        ):
            print(
                f"epoch {epoch:03d} "
                f"train_loss={train_metrics['loss']:.5f} "
                f"val_loss={val_metrics['loss']:.5f} "
                f"val_mae={val_metrics['prob_mae']:.5f} "
                f"val_acc={val_metrics['hard_acc']:.4f}"
            )

        if epochs_without_improvement >= args.patience:
            print(f"Early stopping at epoch {epoch}")
            break

    model.load_state_dict(best_state)
    final_train_metrics = evaluate(
        model,
        x_train,
        y_train,
        tasks_train,
        device=device,
        batch_size=args.batch_size,
    )
    final_val_metrics = evaluate(
        model,
        x_val,
        y_val,
        tasks_val,
        device=device,
        batch_size=args.batch_size,
    )

    config = {
        "dataset": str(dataset_path),
        "input_format": VREQ_FORMAT,
        "output_format": OUTPUT_FORMAT,
        "hidden_dim": args.hidden_dim,
        "dropout": args.dropout,
        "epochs": args.epochs,
        "batch_size": args.batch_size,
        "lr": args.lr,
        "weight_decay": args.weight_decay,
        "val_ratio": args.val_ratio,
        "seed": args.seed,
        "best_epoch": best_epoch,
        "device": str(device),
        "num_rows": int(len(x)),
        "num_train": int(len(train_idx)),
        "num_val": int(len(val_idx)),
    }
    metrics = {
        "best_epoch": best_epoch,
        "train": final_train_metrics,
        "val": final_val_metrics,
        "history": history,
    }

    save_checkpoint(output_dir, model, mean, std, config, metrics)

    print(f"Best epoch: {best_epoch}")
    print(f"Validation loss: {final_val_metrics['loss']:.6f}")
    print(f"Validation probability MAE: {final_val_metrics['prob_mae']:.6f}")
    print(f"Validation hard accuracy: {final_val_metrics['hard_acc']:.4f}")
    print(f"Saved model to {output_dir / 'bar_classifier.pt'}")


if __name__ == "__main__":
    main()
